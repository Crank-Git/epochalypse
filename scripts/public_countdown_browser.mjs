import assert from 'node:assert/strict';

export async function checkPublicCountdown(call, evaluate, waitFor, origin, record) {
  await call('Page.navigate', {url: origin + '/events/' + record.id});
  await waitFor("document.querySelector('#time-status')?.textContent.startsWith('Time synchronized')");
  assert.equal(await evaluate("document.querySelector('h1').textContent"), record.title);
  assert.equal(await evaluate("document.querySelector('#event script')"), null);
  assert.equal(await evaluate("document.querySelector('#dns-name').textContent"), record.name);
  assert.equal(await evaluate("document.querySelector('#event-at').dateTime"), record.event_at);
  assert.match(await evaluate('document.body.textContent'), /Recursive TTL values are advisory/);
  assert.match(await evaluate('document.body.textContent'), /not a security boundary/);
  assert.match(await evaluate("document.querySelector('#local-event').textContent"), /Event time \(local\):/);
  await call('Emulation.setDeviceMetricsOverride', {width:320,height:640,deviceScaleFactor:1,mobile:true});
  await evaluate("document.querySelector('h1').textContent = 'x'.repeat(128)");
  assert.equal(await evaluate('document.documentElement.scrollWidth <= innerWidth'), true);
  await evaluate(`document.querySelector('h1').textContent = ${JSON.stringify(record.title)}`);
  await call('Emulation.clearDeviceMetricsOverride');
  await evaluate(`globalThis.savedCountdownFetch = fetch;
    globalThis.savedCountdownNow = Date.now;
    globalThis.savedPerformanceNow = performance.now.bind(performance);
    globalThis.countdownNow = 100;
    globalThis.countdownWall = 100000;
    performance.now = () => countdownNow;
    Date.now = () => countdownWall;
    globalThis.countdownFixture = ${JSON.stringify({...record, server_now:new Date(Date.parse(record.event_at)-1500).toISOString(),authoritative_ttl:999})};
    globalThis.countdownReads = 0;
    fetch = async () => { countdownReads++; return Response.json(countdownFixture); };
    document.querySelector('#sync-time').click();`);
  await waitFor("document.querySelector('#remaining').textContent === '1 whole seconds remain.'");
  await evaluate('countdownNow += 1499; countdownWall += 1499');
  await waitFor("document.querySelector('#remaining').textContent === '0 whole seconds remain.'");
  assert.equal(await evaluate("document.querySelector('#event-state').textContent"), 'Active');
  await evaluate('countdownNow++; countdownWall++');
  await waitFor("document.querySelector('#event-state').textContent === 'Completed'");
  await evaluate(`countdownFixture.server_now = new Date(Date.parse(countdownFixture.event_at) - 10000).toISOString(); countdownNow += 5000; countdownWall += 5000;`);
  await waitFor("document.querySelector('#remaining').textContent === '10 whole seconds remain.'");
  await evaluate(`globalThis.finishOldSample = null;
    fetch = () => new Promise(resolve => { finishOldSample = resolve; });
    document.querySelector('#sync-time').click();`);
  await waitFor('finishOldSample !== null');
  await evaluate(`fetch = async () => Response.json(countdownFixture);
    document.dispatchEvent(new Event('visibilitychange'));
    finishOldSample(Response.json({...countdownFixture, server_now:new Date(Date.parse(countdownFixture.event_at)+1000).toISOString()}));`);
  await waitFor("document.querySelector('#sync-time').disabled === false");
  assert.equal(await evaluate("document.querySelector('#event-state').textContent"), 'Active', 'A sample from before suspension cannot complete the event');
  assert.ok(await evaluate('countdownReads >= 2'), 'Sleep triggers a server time request');
  // The monotonic clock can pause while the system sleeps.
  await evaluate("fetch = async () => { countdownReads++; throw new Error('offline'); }; countdownWall += 5000");
  await waitFor("document.querySelector('#remaining').textContent === 'Time unavailable.'");
  assert.equal(await evaluate("document.querySelector('#event-state').textContent"), 'Event state unavailable.');
  await evaluate('countdownNow += 1000; countdownWall += 1000');
  assert.equal(await evaluate("document.querySelector('#remaining').textContent"), 'Time unavailable.');
  await evaluate("fetch = async () => Response.json({}); document.querySelector('#sync-time').click()");
  await waitFor("document.querySelector('#time-status').textContent === 'Time unavailable. Retry synchronization.'");
  await evaluate("fetch = async () => new Response('', {status:404}); document.querySelector('#sync-time').click()");
  await waitFor("document.querySelector('#sync-time').disabled === false");
  assert.equal(await evaluate("document.querySelector('#remaining').textContent"), 'Time unavailable.');
  await evaluate("fetch = async () => Response.json(countdownFixture); document.dispatchEvent(new Event('visibilitychange'))");
  await waitFor("document.querySelector('#remaining').textContent === '10 whole seconds remain.'");
  await evaluate("document.querySelector('#sync-time').focus()");
  await call('Input.dispatchKeyEvent', {type:'keyDown',key:' ',code:'Space',windowsVirtualKeyCode:32});
  await call('Input.dispatchKeyEvent', {type:'keyUp',key:' ',code:'Space',windowsVirtualKeyCode:32});
  await waitFor("document.querySelector('#sync-time').disabled === false");
  assert.equal(await evaluate("getComputedStyle(document.querySelector('#sync-time')).outlineStyle"), 'solid');
  await evaluate('fetch = savedCountdownFetch; Date.now = savedCountdownNow; performance.now = savedPerformanceNow');
  assert.equal(await evaluate("fetch('/events/aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa').then(r => r.status)"), 404);
}
